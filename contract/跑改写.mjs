// 改前必读：/root/全忆-V20/设计.md
// 语义改写：只输出关键词、限长、空输入不调模型
import { 改写 } from "../改写.mjs";

let 过 = 0, 败 = 0;
const 记 = (名, ok, 注) => { ok ? 过++ : 败++; console.log((ok ? "✓ " : "✗ ") + 名 + (注 ? "  " + 注 : "")); };

let 调了 = 0, 收到 = null;
const 假说 = async (参) => { 调了++; 收到 = 参; return { text: "桌宠 极限 卡住" }; };

const 词 = await 改写({ 查询: "她劝过我什么之后为什么卡住", 说: 假说 });
记("拆出关键词", Array.isArray(词) && 词.length === 3 && 词[0] === "桌宠", JSON.stringify(词));
记("提示词要求只输出词、且温度 0", String(收到?.系统).includes("只输出") && 收到?.温度 === 0, "");
记("温度 0、思考关", 收到?.思考 === false && 收到?.最大 <= 60, "");

const 不要 = await 改写({ 查询: "话".repeat(200), 说: 假说 });
记("超长问题不改写", 不要.length === 0 && 调了 === 1, "调了 " + 调了 + " 次");
const 空 = await 改写({ 查询: "   ", 说: 假说 });
记("空问题不改写", 空.length === 0 && 调了 === 1, "");

const 怪 = await 改写({ 查询: "为什么", 说: async () => ({ text: "\n桌宠，极限、卡住\n" }) });
记("各种分隔符都能拆", 怪.length === 3 && 怪[2] === "卡住", JSON.stringify(怪));

console.log("\n" + 过 + " ✓ · " + 败 + " ✗");
process.exit(败 ? 1 : 0);
