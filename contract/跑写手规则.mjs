// 日记写手的纯函数：指针校验、金句识别、规则版结构
import { 校验, 金句, 规则写手, 抽承诺, 抽判断, 模型提示 } from "../日记写手.mjs";

const 帧 = [
  { seq: 70, t: "2026-09-29T00:30:02+08:00", who: "user", kind: "text", text: "我觉得到顶了" },
  { seq: 73, t: "2026-09-29T00:31:35+08:00", who: "her", kind: "text", text: "2D 的极限，3D 的初始。" },
  { seq: 74, t: "2026-09-29T00:31:52+08:00", who: "user", kind: "text", text: "对，就是这句" },
  { seq: 82, t: "2026-09-29T00:35:40+08:00", who: "user", kind: "text", text: "等我有自己的电脑，我们再战一场" },
];

let 过 = 0, 败 = 0;
const 记 = (名, ok, 注) => { ok ? 过++ : 败++; console.log((ok ? "✓ " : "✗ ") + 名 + (注 ? "  " + 注 : "")); };

记("合法指针通过", 校验("……\n↩ 73, 82", 帧) === true, "");
记("越界指针被拒", 校验("……\n↩ 99999", 帧) === false, "");
记("没有指针被拒", 校验("……没有指针", 帧) === false, "");
记("金句认得出「对，就是这句」", 金句(帧)?.seq === 73, String(金句(帧)?.seq));
记("规则写手带着原话和指针", (() => {
  const 文 = 规则写手("2026-09-29", 帧, 抽承诺(帧));
  return 文.includes("2D 的极限") && /↩\s*70/.test(文) && 校验(文, 帧);
})(), "");
记("承诺认出「等我有了电脑」", 抽承诺(帧).length === 1 && 抽承诺(帧)[0].触发.条件.includes("电脑"), JSON.stringify(抽承诺(帧)[0]?.触发));

记("超长原话会被截断（不膨胀日记）", (() => {
  const 长帧 = [{ seq: 1, t: "2026-10-01T10:00:00+08:00", who: "her", kind: "text", text: "长".repeat(5000) }];
  const 文 = 规则写手("2026-10-01", 长帧, []);
  return 文.length < 800 && 文.includes("…");
})(), "");
记("没有「他」的帧也能写出短日记", (() => {
  const 只她 = [
    { seq: 1, t: "2026-10-01T10:00:00+08:00", who: "her", kind: "text", text: "开始查宿主日志。" },
    { seq: 2, t: "2026-10-01T10:05:00+08:00", who: "her", kind: "text", text: "日志里没有加窗记录。" },
  ];
  const 文 = 规则写手("2026-10-01", 只她, []);
  return 文.includes("今天记下的是") && 文.length < 800 && 校验(文, 只她);
})(), "");
记("长判断被截到 200 字以内", 抽判断([{ seq: 3, t: "2026-10-01T10:00:00+08:00", who: "her", kind: "text", text: "我觉得" + "啊".repeat(999) }])[0].内容.length <= 201, "");

记("提示词用用户指定的名字", 模型提示({ 天: "2026-09-29", 帧, 称呼: { 名字: "默风", 代词: "他" } }).includes("「默风」"), "");
记("外号也进提示词", 模型提示({ 天: "2026-09-29", 帧, 称呼: { 名字: "默风", 外号: ["小鱼"] } }).includes("外号「小鱼」"), "");
记("明确说「不需要每句叫名字」", 模型提示({ 天: "2026-09-29", 帧, 称呼: {} }).includes("不需要每句都叫名字"), "");
记("没设名字时用代词兜底", 模型提示({ 天: "2026-09-29", 帧, 称呼: {} }).includes("「他」"), "");

console.log("\n" + 过 + " ✓ · " + 败 + " ✗");
process.exit(败 ? 1 : 0);
